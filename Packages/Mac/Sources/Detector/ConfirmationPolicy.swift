//  ConfirmationPolicy — когда порт подтверждает держащееся состояние. C-009, инвариант 24.
//
//  Путь, на котором решается срок подтверждения, живёт в этом файле целиком, и срок в нём не
//  написан ни одним числом секунд: он выводится из `signalTtlSeconds`, пришедшего в точку
//  приёма Ш5. Контракт называет только верхнюю границу — «разрыв меньше срока», — а запас
//  оставляет реализации. Запас здесь назван, и тест его наблюдает (Ш6 (iii)):
//
//  * пара «вид + источник» подтверждается на первом шаге наблюдения, на котором с `observedAt`
//    её прошлой публикации прошло не меньше ПОЛОВИНЫ срока (`confirmationShare`);
//  * шаг наблюдения не длиннее ЧЕТВЕРТИ срока (`longestStepShare`).
//
//  Отсюда граница, которая и есть инвариант 24: разрыв между `observedAt` двух публикаций
//  одной пары не больше половины срока плюс один шаг — то есть не больше трёх четвертей
//  срока, строго меньше `signalTtlSeconds`, — при шаге, который наблюдение выдерживает.
//
//  Почему координата отсчёта — `observedAt`, а не момент собственной публикации. Временная
//  координата публикации в C-009 одна: инвариант 24 вторым предложением своего пункта
//  называет подтверждение «тем же значением с новым `observedAt`, от которого
//  `signalTtlSeconds` отсчитывается заново», инвариант 25 считает возраст последнего по
//  `observedAt`, а поля момента публикации у `MeetingSignal` нет вовсе. Отсчёт от момента
//  собственной публикации выдерживает первую фразу инварианта 24 и ломает инвариант 25 на
//  величину отставания снимка от часов: у держащегося состояния появляется промежуток без
//  актуального сигнала, и потребитель роняет пару. Разбор — MEE-266, MEE-267.
//
//  Граница этого отсчёта названа: источник, у которого снимок отстаёт от часов наблюдения
//  не меньше чем на половину срока, подтверждается на каждом шаге. Публикаций это добавляет,
//  инварианта 25 не ломает; штатному источнику такое отставание не свойственно — он метит
//  снимок теми же часами и в том же шаге.

import Foundation

enum ConfirmationPolicy {

    /// Доля срока, после которой держащееся состояние подтверждается публикацией.
    static let confirmationShare = 0.5

    /// Наибольшая доля срока, которую может занять один шаг наблюдения.
    static let longestStepShare = 0.25

    /// Возраст прошлой публикации пары, начиная с которого она подтверждается.
    static func confirmationAge(signalTtlSeconds: Double) -> TimeInterval {
        signalTtlSeconds * confirmationShare
    }

    /// Шаг наблюдения: предпочтительный, но не длиннее доли срока.
    static func step(preferred: TimeInterval, signalTtlSeconds: Double) -> TimeInterval {
        min(preferred, signalTtlSeconds * longestStepShare)
    }

    /// Пора ли подтверждать пару, чья прошлая публикация помечена `lastObservedAt`, в момент `now`.
    ///
    /// `now` — показание часов наблюдения (Ш6), `lastObservedAt` — координата прошлой публикации
    /// (Ш4 (ii)). Величины остаются двумя; сроку они дают разные концы, а не одно значение.
    ///
    /// Часы, пошедшие назад, подтверждение не откладывают: возраст меньше нуля — тоже «пора».
    /// Иначе перевод часов машины назад растянул бы разрыв сверх срока. Тем же условием закрыт
    /// источник, пометивший снимок моментом впереди часов наблюдения.
    static func isDue(lastObservedAt: Date, now: Date, signalTtlSeconds: Double) -> Bool {
        let age = now.timeIntervalSince(lastObservedAt)
        return age < 0 || age >= confirmationAge(signalTtlSeconds: signalTtlSeconds)
    }
}
