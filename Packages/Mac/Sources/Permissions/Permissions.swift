//  Permissions
//
//  Модуль: permissions · Владелец: DEV-1 · Слой: адаптер системного API
//
//  Каталог принадлежит владельцу модуля: файлы здесь изменяет только он (П1).
//  Всё, что пересекает границу модуля, описано контрактом архитектора и меняется
//  только через interface-request (П2, П6). Границы и запреты — docs/module-map.md.
//
//  Реализует C-007 (MEE-11, `PermissionsPort`) типом `SystemPermissions` и C-008 (MEE-12,
//  `PowerPort`) типом `SystemPower`. Больше публичных объявлений у модуля нет: инвариант 10 обоих
//  контрактов требует хотя бы один собственный публичный тип и запрещает в публичных сигнатурах
//  всё, кроме объединения разрешённых списков.
//
//  Устройство — по швам перечня MEE-74:
//
//  * 1.а — текущий статус права подставляем в тесте: `StatusSource`;
//  * 1.б — исход системного чтения подставляем в тесте, перевод в `PermissionStatus` остаётся
//    предметом проверки: `SystemReader` → `StatusTranslation`;
//  * 2 — источники системных уведомлений питания (`PowerSignalSource`), регистрации login item
//    (`LoginItemRegistry`), открытия раздела настроек (`SettingsOpener`), активации приложения
//    (`ActivationSource`) и взятия системного удержания (`SystemHoldService`) подставляемы;
//    список удержаний, взятых модулем, читается из `HoldRegistry`.
//
//  Модуль не рисует UI, ничего не пишет на диск, не создаёт process tap и не поднимает
//  системного диалога права «Универсальный доступ»: доверие читается `AXIsProcessTrusted()` —
//  вызовом без параметра опций (инвариант 16 C-007).
